function chapterPage(config, subject, ch, entry, order, written) {
  const { meta, html, minutes } = entry;
  const idx = order.findIndex((c) => c.slug === ch.slug);
  const neighbour = (step) => {
    for (let j = idx + step; j >= 0 && j < order.length; j += step) {
      if (written.has(`${subject.slug}/${order[j].slug}`)) return order[j];
    }
    return null;
  };
  const prev = neighbour(-1), next = neighbour(1);
  const pager = `<nav class="pager" aria-label="Chapters">${prev ? `<a href="../${prev.slug}/">Previous: ${esc(prev.title)}</a>` : '<span></span>'}${next ? `<a href="../${next.slug}/">Next: ${esc(next.title)}</a>` : ''}</nav>`;

  const practise = (meta.practise || []).map((p) => {
    const [id, label] = p.split('|').map((x) => x.trim());
    const [region, level] = id.split('/');
    const sub = config.subjects.find((s) => s.game && s.game.region === region);
    return `<li><a href="../../../${config.gamePath}#/${region}/level/${level}">${esc(sub.game.name)} ${esc(level)}: ${esc(label)}</a></li>`;
  });
  const practiseHtml = practise.length ? `<h2>Practise in the game</h2><ul>${practise.join('')}</ul>` : '';
  const sources = (meta.sources || []).map((s) => {
    const [label, url] = s.split('|').map((x) => x.trim());
    return `<li><a href="${esc(url)}">${esc(label)}</a></li>`;
  }).join('');
  const body = `<main id="main"><div class="wrap narrow">
<article class="chapter">
<p class="crumbs"><a href="../../../">Home</a> / <a href="../">${esc(subject.title)}</a></p>
<h1>${esc(meta.title)}</h1>
<p class="meta">${minutes} min read</p>
<p class="intro-summary">${esc(meta.summary)}</p>
${html}
<div class="after">
${practiseHtml}
<h2>Where to check these facts</h2>
<ul>${sources}</ul>
<p>Found a mistake? <a href="${esc(config.reportUrl)}">See how to report it</a>.</p>
</div>
${pager}
</article>
</div></main>`;
  return layout({ config, depth: 3, title: `${meta.title} | ${subject.title} | ${config.name}`, description: meta.summary, body, current: 'subjects' });
}

