function chapterCounts(subject, written) {
  const total = subject.groups.reduce((n, g) => n + g.chapters.length, 0);
  const done = subject.groups.reduce((n, g) => n + g.chapters.filter((c) => written.has(`${subject.slug}/${c.slug}`)).length, 0);
  return { total, done };
}

