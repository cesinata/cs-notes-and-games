// ---------- main ----------

async function main() {
  const config = JSON.parse(await readFile(path.join(SRC, 'site.config.json'), 'utf8'));
  if (typeof config.reportUrl !== 'string' || !config.reportUrl.startsWith('https://')) err('site.config.json: reportUrl is missing or not an https address.');

  // Find the written chapters.
  const chapters = new Map(); // "subject/chapter" -> { meta, html, minutes, grade, words }
  const outline = new Map(config.subjects.map((s) => [s.slug, new Set(s.groups.flatMap((g) => g.chapters.map((c) => c.slug)))]));
  const subjectsDir = path.join(SRC, 'subjects');
  const dirs = existsSync(subjectsDir) ? await readdir(subjectsDir, { withFileTypes: true }) : [];
  for (const d of dirs.filter((x) => x.isDirectory())) {
    if (!outline.has(d.name)) { err(`hub-src/subjects/${d.name}: not a subject in site.config.json.`); continue; }
    for (const f of (await readdir(path.join(subjectsDir, d.name))).filter((x) => x.endsWith('.md'))) {
      const slug = f.replace(/\.md$/, '');
      const file = `hub-src/subjects/${d.name}/${f}`;
      const { meta, body } = parseFrontMatter(await readFile(path.join(subjectsDir, d.name, f), 'utf8'), file);
      const stats = checkChapter(file, meta, body, config, outline.get(d.name).has(slug));
      chapters.set(`${d.name}/${slug}`, { meta, html: mdToHtml(body), ...stats });
    }
  }

  // Outline hygiene.
  const seen = new Set();
  for (const s of config.subjects) for (const g of s.groups) for (const c of g.chapters) {
    const k = `${s.slug}/${c.slug}`;
    if (seen.has(k)) err(`site.config.json: duplicate chapter slug ${k}.`);
    seen.add(k);
    if (c.slug !== slugify(c.title)) warn(`site.config.json: ${k} does not match its title. The file name must be ${c.slug}.md.`);
  }

  // Report.
  console.log(`\nChapters written: ${chapters.size}`);
  for (const [k, c] of chapters) console.log(`  ${k.padEnd(48)} ${String(c.words).padStart(5)} words  ${c.minutes} min  grade ~${c.grade}`);
  const totalOutline = [...outline.values()].reduce((n, s) => n + s.size, 0);
  console.log(`Outline: ${totalOutline} chapters across ${config.subjects.length} subjects (${chapters.size} written).`);
  for (const w of warnings) console.log(`WARNING ${w}`);
  for (const e of errors) console.log(`ERROR   ${e}`);

  if (errors.length) { console.log(`\n${errors.length} error(s). Nothing was built.`); process.exit(1); }
  if (CHECK_ONLY) { console.log('\nCheck finished. Nothing was written.'); return; }

  // The game must already be in game/, or the build would overwrite it with the hub.
  if (!existsSync(path.join(root, config.gamePath, 'index.html'))) {
    console.log(`\nERROR   ${config.gamePath}index.html is missing. Move the game into ${config.gamePath} first, then build.`);
    process.exit(1);
  }

  // Clear only the folders this script owns, then write.
  for (const d of ['subjects', 'about']) await rm(path.join(root, d), { recursive: true, force: true });
  const write = async (rel0, content) => {
    const p = path.join(root, rel0);
    await mkdir(path.dirname(p), { recursive: true });
    await writeFile(p, content);
  };
  const written = new Set(chapters.keys());
  await write('index.html', homePage(config, written));
  await write('404.html', notFoundPage(config));
  await write('about/index.html', aboutPage(config));
  await write('.nojekyll', '');
  for (const s of config.subjects) {
    await write(`subjects/${s.slug}/index.html`, subjectPage(config, s, written, chapters));
    const order = s.groups.flatMap((g) => g.chapters);
    for (const c of order) {
      const key = `${s.slug}/${c.slug}`;
      if (written.has(key)) await write(`subjects/${s.slug}/${c.slug}/index.html`, chapterPage(config, s, c, chapters.get(key), order, written));
    }
  }
  console.log(`\nBuilt ${1 + 1 + 1 + config.subjects.length + chapters.size} pages.`);
}

main().catch((e) => { console.error(e); process.exit(1); });
