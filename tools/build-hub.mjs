// build-hub.mjs
// Builds the CS Notes & Games hub (the learning pages) from plain Markdown files.
// Plain Node 22+, no npm packages.
//
//   node tools/build-hub.mjs --check   only check the chapters (voice, reading level, front matter); write nothing
//   node tools/build-hub.mjs           check, then build the pages into the repo root
//
// Input:   hub-src/site.config.json            name, tagline, subjects, chapter outline
//          hub-src/subjects/<subject>/<chapter>.md   one file per written chapter (the file name is the chapter slug)
// Output:  index.html, about/, subjects/, 404.html, .nojekyll   (all generated; do not edit by hand)
// The game lives in game/ and is not touched by this script.

import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(root, 'hub-src');
const args = process.argv.slice(2);
const CHECK_ONLY = args.includes('--check');
const GENERATED = '<!-- Generated by tools/build-hub.mjs. Edit hub-src/ and rebuild; do not edit this file. -->';

const errors = [];
const warnings = [];
const err = (m) => errors.push(m);
const warn = (m) => warnings.push(m);

// ---------- small helpers ----------

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const slugify = (t) => t.toLowerCase().replace(/&/g, 'and').replace(/'/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const safeUrl = (u) => /^(https:\/\/|mailto:|#|\.{0,2}\/)/.test(u);
const rel = (depth) => (depth === 0 ? './' : '../'.repeat(depth));

// ---------- front matter ----------
// Supports "key: value" lines and lists written as "- item" lines under "key:".

function parseFrontMatter(raw, file) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) { err(`${file}: missing front matter (--- block at the top).`); return { meta: {}, body: raw }; }
  const meta = {};
  let key = null;
  for (const line of m[1].split(/\r?\n/)) {
    if (!line.trim()) continue;
    const item = line.match(/^-\s+(.*)$/);
    if (item && key) { (meta[key] ||= []).push(item[1].trim()); continue; }
    const kv = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (kv) { key = kv[1]; if (kv[2] !== '') meta[key] = kv[2].trim(); else meta[key] = []; continue; }
    err(`${file}: cannot read front matter line "${line}".`);
  }
  return { meta, body: m[2] };
}

// ---------- Markdown (a small, strict subset) ----------

function inline(text) {
  const codes = [];
  let s = text.replace(/`([^`]+)`/g, (_, c) => { codes.push(c); return `\u0000${codes.length - 1}\u0000`; });
  s = esc(s);
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (m, t, u) => {
    const url = u.replace(/&amp;/g, '&');
    return safeUrl(url) ? `<a href="${esc(url)}">${t}</a>` : t;
  });
  s = s.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  s = s.replace(/(^|[^*])\*([^*\s][^*]*?)\*(?!\*)/g, '$1<em>$2</em>');
  s = s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${esc(codes[i])}</code>`);
  return s;
}

const isBlockStart = (l) => /^(#{2,4}\s|[-*]\s|\d+\.\s|>|```|:::|\|)/.test(l);

function mdToHtml(md) {
  const lines = md.replace(/\r/g, '').split('\n');
  const out = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }

    const fence = line.match(/^```(.*)$/);
    if (fence) {
      const buf = []; i++;
      while (i < lines.length && !/^```/.test(lines[i])) buf.push(lines[i++]);
      i++;
      out.push(`<pre><code>${esc(buf.join('\n'))}</code></pre>`);
      continue;
    }

    const block = line.match(/^:::(\w+)\s*(.*)$/);
    if (block) {
      const [, name, title] = block;
      const buf = []; i++;
      while (i < lines.length && !/^:::\s*$/.test(lines[i])) buf.push(lines[i++]);
      i++;
      if (name === 'check') {
        const pairs = []; let q = null;
        for (const l of buf) {
          const mq = l.match(/^Q:\s*(.*)$/), ma = l.match(/^A:\s*(.*)$/);
          if (mq) q = mq[1]; else if (ma && q !== null) { pairs.push([q, ma[1]]); q = null; }
        }
        out.push('<div class="check">' + pairs.map(([qq, aa]) => `<details><summary>${inline(qq)}</summary><p>${inline(aa)}</p></details>`).join('') + '</div>');
      } else if (name === 'deeper') {
        out.push(`<details class="deeper"><summary>${esc(title || 'Go deeper')}</summary>${mdToHtml(buf.join('\n'))}</details>`);
      } else if (name === 'example') {
        out.push(`<aside class="example"><p class="example-title">${inline(title || 'Example')}</p>${mdToHtml(buf.join('\n'))}</aside>`);
      } else {
        err(`Unknown block ":::${name}".`);
      }
      continue;
    }

    const h = line.match(/^(#{2,4})\s+(.*)$/);
    if (h) { const level = h[1].length; out.push(`<h${level} id="${slugify(h[2])}">${inline(h[2])}</h${level}>`); i++; continue; }

    if (/^\|/.test(line) && i + 1 < lines.length && /^\|[\s:|-]+\|?\s*$/.test(lines[i + 1])) {
      const cells = (l) => l.replace(/^\||\|\s*$/g, '').split('|').map((c) => c.trim());
      const head = cells(line); i += 2;
      const rows = [];
      while (i < lines.length && /^\|/.test(lines[i])) rows.push(cells(lines[i++]));
      out.push('<div class="table-scroll"><table><thead><tr>' + head.map((c) => `<th scope="col">${inline(c)}</th>`).join('') + '</tr></thead><tbody>' +
        rows.map((r) => '<tr>' + r.map((c) => `<td>${inline(c)}</td>`).join('') + '</tr>').join('') + '</tbody></table></div>');
      continue;
    }

    if (/^[-*]\s/.test(line)) {
      const items = [];
      while (i < lines.length && /^[-*]\s/.test(lines[i])) items.push(lines[i++].replace(/^[-*]\s+/, ''));
      out.push('<ul>' + items.map((t) => `<li>${inline(t)}</li>`).join('') + '</ul>');
      continue;
    }
    if (/^\d+\.\s/.test(line)) {
      const items = [];
      while (i < lines.length && /^\d+\.\s/.test(lines[i])) items.push(lines[i++].replace(/^\d+\.\s+/, ''));
      out.push('<ol>' + items.map((t) => `<li>${inline(t)}</li>`).join('') + '</ol>');
      continue;
    }
    if (/^>/.test(line)) {
      const buf = [];
      while (i < lines.length && /^>/.test(lines[i])) buf.push(lines[i++].replace(/^>\s?/, ''));
      out.push(`<blockquote>${mdToHtml(buf.join('\n'))}</blockquote>`);
      continue;
    }

    const buf = [];
    while (i < lines.length && lines[i].trim() && !isBlockStart(lines[i])) buf.push(lines[i++]);
    out.push(`<p>${inline(buf.join(' '))}</p>`);
  }
  return out.join('\n');
}

// ---------- checks: voice, reading level, front matter ----------

const BANNED = /\b(journey|unlock(?:ing|s)?|dive in|delve|seamless(?:ly)?|whether you'?re|not just|game-?changer|landscape|in today'?s|embark|leverage|robust|crucial|tapestry)\b/i;
const EMOJI = /\p{Extended_Pictographic}/u;

function proseOf(body) {
  // The text a beginner reads first: no "Go deeper", no code, no tables, no check blocks.
  return body
    .replace(/:::deeper[\s\S]*?\n:::\s*(\n|$)/g, '\n')
    .replace(/:::check[\s\S]*?\n:::\s*(\n|$)/g, '\n')
    .replace(/```[\s\S]*?```/g, '\n')
    .split('\n')
    .filter((l) => l.trim() && !/^(#{1,4}\s|\||:::)/.test(l))
    .map((l) => l.replace(/^([-*]|\d+\.)\s+/, '').replace(/[*`_]/g, '').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1'));
}

function syllables(word) {
  let w = word.toLowerCase().replace(/[^a-z]/g, '');
  if (!w) return 0;
  if (w.length <= 3) return 1;
  w = w.replace(/(?:[^laeiouy]es|ed|[^laeiouy]e)$/, '').replace(/^y/, '');
  const m = w.match(/[aeiouy]{1,2}/g);
  return m ? m.length : 1;
}

// Flesch-Kincaid grade. The syllable count is a rough guess, so treat the number as a guide only.
function gradeOf(lines) {
  const text = lines.join(' ');
  const sentences = Math.max(1, lines.reduce((n, l) => n + Math.max(1, (l.match(/[.!?]+(\s|$)/g) || []).length), 0));
  const words = text.match(/[A-Za-z][A-Za-z'-]*/g) || [];
  if (!words.length) return { grade: 0, words: 0 };
  const syl = words.reduce((n, w) => n + syllables(w), 0);
  const grade = 0.39 * (words.length / sentences) + 11.8 * (syl / words.length) - 15.59;
  return { grade: Math.round(grade * 10) / 10, words: words.length };
}

function checkChapter(file, meta, body, config, knownSlug) {
  if (!meta.title) err(`${file}: no title in front matter.`);
  if (!meta.summary) err(`${file}: no summary in front matter.`);
  const sources = Array.isArray(meta.sources) ? meta.sources : [];
  if (sources.length < 2) err(`${file}: needs at least 2 sources (label | https address).`);
  for (const s of sources) {
    const [label, url] = s.split('|').map((x) => x.trim());
    if (!label || !url || !/^https:\/\//.test(url)) err(`${file}: source "${s}" must look like "label | https://address".`);
  }
  const checks = Array.isArray(meta.check) ? meta.check : [];
  if (checks.length < 3) err(`${file}: needs at least 3 "check" lines (claim | where to confirm it).`);
  if (!knownSlug) warn(`${file}: this chapter is not in the outline in site.config.json, so it will not be listed.`);

  const regions = new Set(config.subjects.filter((s) => s.game).map((s) => s.game.region));
  for (const p of Array.isArray(meta.practise) ? meta.practise : []) {
    const [id, label] = p.split('|').map((x) => x.trim());
    const m = id && id.match(/^(\w+)\/(\d+\.\d+)$/);
    if (!m || !label) err(`${file}: practise "${p}" must look like "net/5.2 | Level name".`);
    else if (!regions.has(m[1])) err(`${file}: practise region "${m[1]}" is not a game region in the config.`);
  }

  const prose = proseOf(body);
  const { grade, words } = gradeOf(prose);
  if (grade > 9.5) warn(`${file}: reading level looks like grade ${grade} (aim for 7 to 9). Shorten sentences and swap long words.`);
  const bad = new Set();
  for (const l of prose) {
    const b = l.match(BANNED); if (b) bad.add(b[0]);
    if (EMOJI.test(l)) warn(`${file}: emoji in the middle of text: "${l.slice(0, 50)}...". Emoji are fine in headings and lists, not in paragraphs.`);
    if (/!/.test(l)) warn(`${file}: exclamation mark: "${l.slice(0, 50)}..."`);
  }
  if (bad.size) warn(`${file}: words the voice guide avoids: ${[...bad].join(', ')}.`);
  const all = (meta.title || '') + ' ' + (meta.summary || '');
  if (BANNED.test(all)) warn(`${file}: the title or summary uses a word the voice guide avoids.`);
  return { grade, words, minutes: Math.max(1, Math.round(words / 200)) };
}

